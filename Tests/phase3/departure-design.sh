#!/usr/bin/env bash
#
# departure-design.sh -- P3.2 departure feasibility and lifecycle contract.
#
# Contract: docs/PHASE3-PLAN.md section 3 P3.2 (lines ~121-140).
#
# This is a DESIGN/AUDIT driver.  It changes no Src/ file; it:
#
#   1. builds the shipped display-free server core and links the P3.2
#      departure-design fixture against it (Src/sobj minus server_main.o);
#   2. runs the fixture (twice, requiring identical output) to freeze the
#      ordinary two-human reference and characterize the candidate removal
#      seam against the approved D3-D departure policy;
#   3. freezes/compares the ordinary two-human reference hash in
#      Tests/phase3/fixtures/two-human-ordinary.sha256;
#   4. audits the read-only source for the exact primitives the removal
#      contract depends on and reports whether existing primitives suffice.
#
# All generated binaries/logs live OUTSIDE the checkout.
#
#   bash Tests/phase3/departure-design.sh [--evidence DIR]
#
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HARNESS="$REPO/Tests/phase3"
EVIDENCE="${XTANK_P3_EVIDENCE:-/tmp/opencode/xtank-phase3/p3.2/design}"
GOLDEN="$HARNESS/fixtures/two-human-ordinary.sha256"

while [ $# -gt 0 ]; do
	case "$1" in
	  --evidence) EVIDENCE="$2"; shift 2 ;;
	  *) echo "usage: departure-design.sh [--evidence DIR]" >&2; exit 2 ;;
	esac
done

mkdir -p "$EVIDENCE"
WORK="$EVIDENCE/work"
mkdir -p "$WORK"

log()  { printf '%s\n' "$*"; }
fail() { printf 'DEPARTURE-DESIGN FAIL: %s\n' "$*" >&2; exit 1; }

# Same feature defines as the shipped server build (Src/GNUmakefile SCFLAGS).
DEFS="-DUNIX -DS1024x864 -DKEYPAD_DETECT -DSTINGY_REDRAW -DBATCH_LINES \
-DBATCH_POINTS -DBATCH_COLOR_LINES -DCODE_SIZE=0x20000 -DSTACK_SIZE=0x8000 \
-DNEW_LIMITS -DSLOWER -DMULTI_SYNC -DTHREAD_SWAPCONTEXT -DNULL_BACKEND \
-DSERVER_ONLY"

log "== building the shipped server core (make phase1-server phase1-core)"
( cd "$REPO" && make phase1-server phase1-core ) > "$WORK/build.out" 2>&1 || \
	fail "server/core build failed (see $WORK/build.out)"

[ -d "$REPO/Src/sobj" ] || fail "server object tree missing"

# Core objects without the server entry point (the fixture provides main()).
# shellcheck disable=SC2046
CORE_OBJS=$(ls "$REPO"/Src/sobj/*.o | grep -v '/server_main.o$')
[ -n "$CORE_OBJS" ] || fail "no core objects"

log "== compiling the departure-design fixture against the server core"
# shellcheck disable=SC2086
gcc -O0 -g -w $DEFS -I"$REPO/Src" -I"$REPO/Src/Include" \
	-DXTANK_DIR="\"$REPO/Src/..\"" -DALLDEFINES="\"p3.2 departure design fixture\"" \
	-o "$WORK/departure-design_fixture" \
	"$HARNESS/departure-design_fixture.c" $CORE_OBJS -lm \
	> "$WORK/fixture-build.out" 2>&1 || \
	fail "fixture build failed (see $WORK/fixture-build.out)"

log "== running the departure-design fixture"
if ! "$WORK/departure-design_fixture" "$REPO" > "$WORK/fixture1.out" 2>&1; then
	cat "$WORK/fixture1.out" >&2
	fail "fixture failed"
fi
grep -q 'DEPARTURE-DESIGN PASS' "$WORK/fixture1.out" || \
	fail "fixture did not report PASS"
FAILLINE=$(grep -c '\[FAIL\]' "$WORK/fixture1.out" || true)
[ "$FAILLINE" = "0" ] || fail "fixture reported $FAILLINE failing check(s)"
NCHECKS=$(grep -o 'checks=[0-9]*' "$WORK/fixture1.out" | grep -o '[0-9]*')
log "    $(grep -m1 'DEPARTURE-DESIGN PASS' "$WORK/fixture1.out")"

log "== determinism: repeat the fixture"
"$WORK/departure-design_fixture" "$REPO" > "$WORK/fixture2.out" 2>&1 || \
	fail "fixture repeat failed"
cmp "$WORK/fixture1.out" "$WORK/fixture2.out" >/dev/null || \
	fail "fixture repeats differ"
log "    two fixture runs identical"

# ---- freeze the ordinary two-human reference hash ----------------------
HASH=$(grep -m1 'DEPARTURE-DESIGN hash-ordinary=' "$WORK/fixture1.out" | \
	sed 's/.*hash-ordinary=\([0-9a-f]*\).*/\1/')
[ -n "$HASH" ] || fail "fixture did not print an ordinary two-human hash"
log "== ordinary two-human reference: $HASH"
if [ -f "$GOLDEN" ]; then
	EXPECT=$(sed -n 's/^hash=//p' "$GOLDEN")
	if [ "$HASH" != "$EXPECT" ]; then
		fail "ordinary two-human reference drifted: $HASH != $EXPECT"
	fi
	log "    matches frozen fixture $GOLDEN"
else
	mkdir -p "$(dirname "$GOLDEN")"
	{
		printf '# P3.2 ordinary two-human reference (frozen before core changes).\n'
		printf '# Two terminal-free humans, combat1/Vanguard, seed 114336,\n'
		printf '# deterministic %s-tick script, bot-free.\n' \
			"$(grep -m1 -o 'ticks=[0-9]*' "$WORK/fixture1.out" | \
			   grep -o '[0-9]*')"
		printf 'hash=%s\n' "$HASH"
	} > "$GOLDEN"
	log "    FROZE new fixture $GOLDEN (hash=$HASH)"
fi

# ---- read-only source audit -------------------------------------------
log "== source audit (read-only)"
AUD="$EVIDENCE/source-audit.txt"
{
	echo "# P3.2 read-only primitive audit (generated by departure-design.sh)"
	echo
	echo "## inactivate_vehicle (Src/vehicle.c): no explode/score/death/RNG"
	sed -n '/^void inactivate_vehicle/,/^}/p' "$REPO/Src/vehicle.c" | \
		grep -nE 'zap_specials|clrflag|thread_kill|server_player_terminal|real_map' || true
	echo
	echo "## kill_vehicle (Src/vehicle.c): explodes, deaths++, score, RNG, respawn"
	sed -n '/^kill_vehicle/,/^}/p' "$REPO/Src/vehicle.c" | grep -nE \
		'explode_vehicle|deaths\+\+|score|explode_location|VS_permanently_dead|inactivate_vehicle' || true
	echo
	echo "## unmake_vehicle (Src/vehicle.c): frees thread/stack/special storage"
	sed -n '/^unmake_vehicle/,/^}/p' "$REPO/Src/vehicle.c" | grep -nE \
		'free\(|unmake_specials' || true
	echo
	echo "## projectile owner references (must stay valid across a departure)"
	grep -nE 'b->owner' "$REPO/Src/update.c" "$REPO/Src/hit.c" \
		"$REPO/Src/collision.c" "$REPO/Src/disc.c" | head -20 || true
	echo
	echo "## intent queue: held controls are per-player but cancel is all-or-nothing"
	grep -nE 'held_fire|held_aim|held_chase|held_standoff|void|intent_reset' \
		"$REPO/Src/intent.c" | grep -E 'held_|intent_reset' | head -20 || true
	echo
	echo "## live/dead list swap-remove (Src/animate.c)"
	grep -nE 'dead_vehicles\[num_veh_dead\+\+\]|live_vehicles\[i\] = live_vehicles\[--num_veh_alive\]|dead_vehicles\[i\] = dead_vehicles\[--num_veh_dead\]|unmake_vehicle\(v\)' \
		"$REPO/Src/animate.c" || true
} > "$AUD"

# Hard assertions on the contract's load-bearing facts.
grep -q 'zap_specials' "$AUD" || fail "audit: inactivate_vehicle facts missing"
grep -q 'unmake_specials' "$AUD" || fail "audit: unmake_vehicle facts missing"
grep -q 'explode_vehicle' "$AUD" || fail "audit: kill_vehicle facts missing"
grep -q 'intent_reset' "$AUD" || fail "audit: intent facts missing"
log "    audit written to $AUD"

# Confirm the identified smallest seam does NOT yet exist.
if grep -qE '\bintent_cancel_player\b' "$REPO/Src/intent.c" "$REPO/Src/Include/intent.h"; then
	log "    note: intent_cancel_player already present"
else
	log "    seam required: intent_cancel_player(player) is absent (expected)"
fi

log ""
log "P3.2 DEPARTURE-DESIGN PASS (checks=$NCHECKS, ordinary hash=$HASH)"
